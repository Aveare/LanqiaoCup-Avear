// 10ms软件消抖延时函数（12MHz晶振）
void delay10ms()
{
    unsigned int i, j;
    for(i = 20; i > 0; i--)
        for(j = 248; j > 0; j--);
}

// 57μs精准波形延时函数（12MHz晶振）
void delay57us()
{
    unsigned char i = 28;
    while(i--);
}

// 独立按键扫描函数
unsigned int Key_Scan()
{
    static bit key_up = 1;  // 按键松开标志
    if((!k1 || !k2 || !k3 || !k4) && key_up)
    {
        key_up = 0;
        delay10ms();  // 软件消抖，替代定时器消抖
        
        if(k1 == 0) return num1;
        else if(k2 == 0) return num2;
        else if(k3 == 0) return num3;
        else if(k4 == 0) return num4;
    }
    else if(k1 && k2 && k3 && k4)
    {
        key_up = 1;
    }
    return 0;
}

// 锯齿波输出函数
void stair_wave()
{
    unsigned char i;
    for(i = 0; i < 255; i++)
    {
        DAC0832 = i;
        delay57us();
    }
}

// 方波输出函数
void square_wave()
{
    unsigned int i;
    DAC0832 = 0xFF;
    for(i = 0; i < 125; i++) delay57us();
    DAC0832 = 0x00;
    for(i = 0; i < 125; i++) delay57us();
}

// 三角波输出函数
void triangle_wave()
{
    unsigned char i;
    for(i = 0; i < 125; i++)
    {
        DAC0832 = i;
        delay57us();
    }
    for(i = 125; i > 0; i--)
    {
        DAC0832 = i;
        delay57us();
    }
}

// 正弦波输出函数
void sine_wave()
{
    unsigned char i;
    for(i = 0; i < 256; i++)
    {
        DAC0832 = sin_table[i];
        delay57us();
    }
}

// 按键处理与波形选择
void Key_Wave_Proc()
{
    key_num = Key_Scan();
    if(key_num != 0)
    {
        wave_mode = key_num;  // 仅在按键按下
    }
		
    switch(wave_mode)
    {
        case 1: square_wave();   break;
        case 2: triangle_wave(); break;
        case 3: stair_wave();    break;
        case 4: sine_wave();     break;
        default: break;
    }
}

void main()
{
    DAC0832 = 0x00;//初始输出低电平
    while(1)
    {
        Key_Wave_Proc();
    }
}