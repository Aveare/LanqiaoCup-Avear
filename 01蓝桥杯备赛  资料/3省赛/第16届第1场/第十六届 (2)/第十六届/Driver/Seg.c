#include <Seg.h>

unsigned char Seg_dula[]={0xC0,0xF9,0xA4,0xB0,0x99,0x92,0x82,0xF8,0x80,0x90,0xFF,0xC6,0xC8,0xC7,0x8C};
unsigned char Seg_wela[]={0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80};
void Seg_Disp(unsigned char wela,dula,point)
{
	unsigned char temp;
	P0=0xFF;
	temp=P2&0x1F;
	temp=temp|0xE0;
	P2=temp;
	temp=P2&0x1F;
	P2=temp;
	
	P0=Seg_wela[wela];
	temp=P2&0x1F;
	temp=temp|0xC0;
	P2=temp;
	temp=P2&0x1F;
	P2=temp;
	
	P0=Seg_dula[dula];
	if(point) P0&=0x7F;
		
	temp=P2&0x1F;
	temp=temp|0xE0;
	P2=temp;
	temp=P2&0x1F;
	P2=temp;
}

